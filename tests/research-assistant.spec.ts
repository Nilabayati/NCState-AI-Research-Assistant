test("PDF export contains only the exact current conversation as image pages", async ({ page }) => {
  await page.goto("/");
  await acknowledge(page);
  await send(page, "OLD-CONVERSATION-SHOULD-NOT-BE-EXPORTED");
  await page.getByRole("button", { name: "New conversation", exact: true }).click();
  await page.getByRole("button", { name: "Start new conversation", exact: true }).click();
  await acknowledge(page);
  const studentContent = "I hope to understand learners’ experiences—what they find meaningful.\n- An exploratory idea.\n\n".repeat(30).trim();
  await send(page, studentContent);

  const visibleMessages = await page.locator(".message-bubble").evaluateAll((bubbles) => bubbles.map((bubble) => {
    const content = bubble.querySelector(".message-content")?.textContent ?? "";
    const offer = bubble.querySelector(".transcript-offer p")?.textContent;
    return offer ? `${content}\n\n${offer}\nCreate PDF · No thanks` : content;
  }));
  const expectedContent = [exactNotice, "I Agree", ...visibleMessages, "Create PDF"].join("").replace(/\r\n|[\n\r\u2028\u2029]/gu, "");

  // Inspect actual text drawn into the exported image pages without pretending
  // that the rasterized PDF exposes editable or reliably extractable text.
  await page.evaluate(() => {
    const browserWindow = window as typeof window & { transcriptDrawnText?: string[] };
    browserWindow.transcriptDrawnText = [];
    const original = CanvasRenderingContext2D.prototype.fillText;
    CanvasRenderingContext2D.prototype.fillText = function (text, x, y, maxWidth) {
      if (this.font.startsWith("18px ")) browserWindow.transcriptDrawnText?.push(text);
      if (maxWidth === undefined) original.call(this, text, x, y);
      else original.call(this, text, x, y, maxWidth);
    };
  });

  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export PDF", exact: true }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/^research-design-transcript-[a-zA-Z0-9_-]+\.pdf$/);
  const filePath = await download.path();
  expect(filePath).not.toBeNull();
  const pdf = await readFile(filePath!);
  const rawPdf = pdf.toString("latin1");
  expect(rawPdf.startsWith("%PDF-")).toBe(true);
  expect((rawPdf.match(/\/Type \/Page\b/g) ?? []).length).toBeGreaterThan(1);
  expect((rawPdf.match(/\/Subtype \/Image\b/g) ?? []).length).toBeGreaterThan(1);
  const drawn = await page.evaluate(() => (window as typeof window & { transcriptDrawnText?: string[] }).transcriptDrawnText?.join(""));
  expect(drawn).toBe(expectedContent);
  expect(drawn).not.toContain("OLD-CONVERSATION-SHOULD-NOT-BE-EXPORTED");
  await expect(page.getByRole("status")).toContainText("the PDF is not tamper-proof");
});

test("the accessible text download preserves the exact current conversation in UTF-8", async ({ page }) => {
  await page.goto("/");
  await acknowledge(page);
  await send(page, "OLD-TEXT-CONVERSATION-MARKER");
  await page.getByRole("button", { name: "New conversation", exact: true }).click();
  await page.getByRole("button", { name: "Start new conversation", exact: true }).click();
  await acknowledge(page);
  const content = "I hope to understand learners’ experiences—especially feedback.\n- My uncertainty is meaning.\n\nA naïve starting point.";
  await send(page, content);
  const visibleMessages = await page.locator(".message-row").evaluateAll((rows) => rows.map((row) => {
    const content = row.querySelector(".message-content")?.textContent ?? "";
    const offer = row.querySelector(".transcript-offer p")?.textContent;
    const messageText = offer ? `${content}\n\n${offer}\nCreate PDF · No thanks` : content;
    const role = row.classList.contains("student-message") ? "Student" : "Tutor · simulated demo response";
    return `${role}\n${messageText}`;
  }));
  const expectedMessages = [
    `Acknowledgement notice\n${exactNotice}`,
    "Student\nI Agree",
    ...visibleMessages,
    "Student\nDownload accessible text transcript",
  ].join("\n\n");

  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download accessible text transcript", exact: true }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/^research-design-transcript-[a-zA-Z0-9_-]+\.txt$/);
  const filePath = await download.path();
  expect(filePath).not.toBeNull();
  const downloadedText = await readFile(filePath!, "utf8");
  expect(downloadedText.split("Message text below is preserved as supplied.\n\n")[1]).toBe(expectedMessages);
  expect(downloadedText).toContain(content);
  expect(downloadedText).not.toContain("OLD-TEXT-CONVERSATION-MARKER");
  await expect(page.getByRole("status")).toContainText("Text transcript downloaded.");
});

