import { readFile } from "node:fs/promises";
import { readFileSync } from "node:fs";
import path from "node:path";
import AxeBuilder from "@axe-core/playwright";
import { expect, test as base, type Download, type Page } from "@playwright/test";

const deploymentUrl = process.env.DEPLOYMENT_BASE_URL;
const source = readFileSync(path.join(process.cwd(), "docs/research-design-tutor-plugin.txt"), "utf8");
const noticeStart = source.indexOf("Research Design Tutor — Before You Begin\n");
const noticeEnd = source.indexOf("\nAfter presenting the notice:", noticeStart);
if (noticeStart < 0 || noticeEnd < 0) throw new Error("Original acknowledgement notice not found.");
const exactNotice = source.slice(noticeStart, noticeEnd);
const firstQuestion = "What is the purpose of your research—what do you hope to understand or find out?";

// Check the actual production assets, including chunks loaded only by PDF export.
const test = base.extend({
  page: async ({ page }, runWithPage) => {
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
    page.on("response", (response) => {
      if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`);
    });
    page.on("requestfailed", (request) => errors.push(`${request.url()}: ${request.failure()?.errorText}`));
    await runWithPage(page);
    expect(errors, "Deployment must load without browser errors or failed assets.").toEqual([]);
  },
});

test.skip(!deploymentUrl, "Deployment checks require DEPLOYMENT_BASE_URL and an already-running target.");

async function openDeployment(page: Page) {
  // A full URL preserves GitHub Pages' repository prefix; goto('/') would discard it.
  const response = await page.goto(deploymentUrl!, { waitUntil: "networkidle" });
  expect(response?.status()).toBe(200);
  await expect(page.getByRole("button", { name: "Get Started", exact: true })).toBeVisible();
  await expect(page.getByText("Responses are locally scripted, not generated by AI.", { exact: false })).toBeVisible();
}

async function openGate(page: Page) {
  await page.getByRole("button", { name: "Get Started", exact: true }).click();
  await expect(page.getByTestId("acknowledgement-notice")).toHaveText(exactNotice);
  expect(await page.getByTestId("acknowledgement-notice").textContent()).toBe(exactNotice);
  await expect(page.getByRole("textbox")).toHaveCount(0);
}

async function agree(page: Page) {
  await page.getByRole("button", { name: "I Agree", exact: true }).click();
  await expect(page.locator(".tutor-message .message-content").last()).toHaveText(firstQuestion);
}

async function send(page: Page, message: string) {
  await page.getByRole("textbox", { name: "Your message to the demo tutor" }).fill(message);
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  await expect(page.locator(".student-message .message-content").last()).toHaveText(message);
}

async function downloadBytes(download: Download) {
  expect(await download.failure()).toBeNull();
  const filePath = await download.path();
  expect(filePath).not.toBeNull();
  return readFile(filePath!);
}

async function checkAccessibilityAndReflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const audit = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa", "wcag22aa"]).analyze();
  expect(audit.violations, JSON.stringify(audit.violations, null, 2)).toEqual([]);
}

test("published assets preserve the source, acknowledgement gate, chat and downloads", async ({ page }) => {
  await openDeployment(page);
  await page.getByRole("button", { name: "Original tutor instructions", exact: true }).click();
  await expect(page.locator(".plugin-source")).toHaveText(source);
  expect(await page.locator(".plugin-source").textContent()).toBe(source);
  const sourceDownload = page.waitForEvent("download");
  await page.getByRole("link", { name: "Download original instructions", exact: true }).click();
  expect(await downloadBytes(await sourceDownload)).toEqual(Buffer.from(source));
  await page.getByRole("button", { name: "Close dialog", exact: true }).click();

  await openGate(page);
  await page.getByRole("button", { name: "I Disagree", exact: true }).click();
  await expect(page.locator(".denied-message[role=alert]")).toHaveText("The tutor cannot continue without acknowledgement of these conditions.");
  await expect(page.getByRole("textbox")).toHaveCount(0);
  await agree(page);
  const studentMessage = "I hope to understand how university students experience feedback.";
  await send(page, studentMessage);
  await expect(page.locator(".tutor-message")).toHaveCount(3); // Includes the refusal before agreement.
  await expect(page.locator(".tutor-message .message-content").last()).not.toHaveText(firstQuestion);
  await checkAccessibilityAndReflow(page);

  const pdfDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export PDF", exact: true }).click();
  const pdf = await pdfDownload;
  expect(pdf.suggestedFilename()).toMatch(/^research-design-transcript-[\w-]+\.pdf$/);
  expect((await downloadBytes(pdf)).subarray(0, 5).toString()).toBe("%PDF-");
  await expect(page.getByRole("status")).toContainText("PDF downloaded.");

  const textDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download accessible text transcript", exact: true }).click();
  const transcript = (await downloadBytes(await textDownload)).toString("utf8");
  expect(transcript).toContain(exactNotice);
  expect(transcript).toContain(firstQuestion);
  expect(transcript).toContain(studentMessage);
  expect(transcript).toContain("I Agree");
  await expect(page.getByRole("status")).toContainText("Text transcript downloaded.");
});

test("a published conversation resets independently and exports only its current messages", async ({ page }) => {
  await openDeployment(page);
  await openGate(page);
  await agree(page);
  await send(page, "OLD-DEPLOYMENT-CONVERSATION-MARKER");
  await page.getByRole("button", { name: "New conversation", exact: true }).click();
  await page.getByRole("button", { name: "Start new conversation", exact: true }).click();
  await expect(page.getByRole("button", { name: /^Your conversation/ })).toBeDisabled();
  await openGate(page);
  await agree(page);
  await expect(page.locator(".message-content")).toHaveCount(1);
  const newMessage = "I want to understand learners’ experiences—CURRENT-DEPLOYMENT-MARKER.";
  await send(page, newMessage);
  const textDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download accessible text transcript", exact: true }).click();
  const transcript = (await downloadBytes(await textDownload)).toString("utf8");
  expect(transcript).toContain(newMessage);
  expect(transcript).not.toContain("OLD-DEPLOYMENT-CONVERSATION-MARKER");
  await page.reload({ waitUntil: "networkidle" });
  await expect(page.getByRole("button", { name: "Get Started", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: /^Your conversation/ })).toBeDisabled();
  await expect(page.getByRole("textbox")).toHaveCount(0);
  await openGate(page);
  await expect(page.getByText(firstQuestion, { exact: true })).toHaveCount(0);
});

test("published mobile screens and dialogs remain accessible and fit the viewport", async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await openDeployment(page);
  await checkAccessibilityAndReflow(page);
  await openGate(page);
  await checkAccessibilityAndReflow(page);
  await agree(page);
  await send(page, "I am curious about collaborative learning.");
  await checkAccessibilityAndReflow(page);
  await page.getByRole("button", { name: "View conditions", exact: true }).click();
  expect(await page.getByRole("dialog").locator(".notice-copy").textContent()).toBe(exactNotice);
  await checkAccessibilityAndReflow(page);
  await page.getByRole("button", { name: "Close conditions", exact: true }).click();
  await page.getByRole("button", { name: "New conversation", exact: true }).click();
  await checkAccessibilityAndReflow(page);
  await page.getByRole("button", { name: "Start new conversation", exact: true }).click();
  await expect(page.getByRole("button", { name: "Get Started", exact: true })).toBeVisible();
});
